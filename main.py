@tool("Create Python File")
def CreateFilePython(derictoryName: str, filename: str, code: str) -> str:
    """
    Create a python file from generated code.
    """

    print("🔥 TOOL EXECUTÉ")

    BASE_DIR = os.path.dirname(os.path.abspath(__file__))

    full_dir = os.path.join(BASE_DIR, "output", derictoryName)
    os.makedirs(full_dir, exist_ok=True)

    filepath = os.path.join(full_dir, filename)

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(code)

    return f"Fichier créé avec succès : {filepath}"

